package day5;

public class DoWhileLoop {

    public static void main(String[] args) {

        int i = 1;
        do {
            System.out.println(i);
            i++;
        } while (i <= 10);

//        10............1

        int j = 10;
        do {
            System.out.println(j);
            j--;
        } while (j >= 1);

    }
}
